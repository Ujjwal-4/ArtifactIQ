# synthetic FAT32 image builder (pure stdlib; used for phase-6 demo evidence)


def _dos_ts(dt: datetime):
    dos_date = ((dt.year - 1980) << 9) | (dt.month << 5) | dt.day
    dos_time = (dt.hour << 11) | (dt.minute << 5) | (dt.second // 2)
    return dos_date, dos_time


def _dir_entry(name8_3: str, ext: str, attr: int, cluster: int, size: int,
               dt: datetime) -> bytes:
    ddate, dtime = _dos_ts(dt)
    name = (name8_3.upper().ljust(8, " ") + ext.upper().ljust(3, " ")).encode("ascii")
    e = bytearray(32)
    e[0:11] = name
    e[11] = attr
    e[13] = ((dt.microsecond // 10000) & 0xFF) if attr & 0x20 else 0  # 10ms tick (file only)
    e[14:16] = dtime.to_bytes(2, "little")      # create time
    e[16:18] = ddate.to_bytes(2, "little")      # create date
    e[18:20] = ddate.to_bytes(2, "little")      # last access date
    e[20:22] = (cluster >> 16).to_bytes(2, "little")  # first cluster (high); 0 for FAT16
    e[22:24] = dtime.to_bytes(2, "little")      # modify time
    e[24:26] = ddate.to_bytes(2, "little")      # modify date
    e[26:28] = (cluster & 0xFFFF).to_bytes(2, "little")  # first cluster (low)
    e[28:32] = size.to_bytes(4, "little")
    return bytes(e)


def _dos_ts(dt: datetime) -> tuple[int, int]:
    dos_date = ((dt.year - 1980) << 9) | (dt.month << 5) | dt.day
    dos_time = (dt.hour << 11) | (dt.minute << 5) | (dt.second // 2)
    return dos_date, dos_time


def make_fat16_image(path: Path, volume_label: str = "AIQDEMO",
                     utc: datetime | None = None) -> dict:
    """Build a small, genuinely valid FAT16 volume image (superfloppy, ~2 MB).

    Real filesystem layout that The Sleuth Kit (pytsk3) can actually open —
    used as synthetic demo evidence for phase 6. Contents:
        /README.TXT, /SYNTHETI.TXT, /DOWNLOAD/TOOLPACK.EXE
    Everything inside (names, timestamps, contents) is synthetic demo staging.
    """
    dt = utc or datetime(2025, 8, 17, 22, 20, 0, tzinfo=timezone.utc)
    SEC = 512
    RESERVE = 1                      # boot sector only
    NCLUSTER = 4090                  # data clusters; >= 4085 so TSK/Windows call it FAT16
    FATSZ = 16                       # sectors per FAT: (4090+2) entries * 2B -> ~16 sectors
    ROOT_ENTRIES = 32                # root directory slots
    ROOT_SECT = ROOT_ENTRIES * 32 // SEC   # 2 sectors
    DATA_START = RESERVE + FATSZ * 2 + ROOT_SECT
    total_sectors = DATA_START + NCLUSTER
    img = bytearray(total_sectors * SEC)

    def put(sector: int, data: bytes):
        img[sector * SEC: sector * SEC + len(data)] = data

    # --- boot sector (FAT16 BPB) -------------------------------------------------
    bs = bytearray(SEC)
    bs[0:3] = b"\xEB\x3C\x90"
    bs[3:11] = b"SYNDEMO1"                            # OEM label (synthetic marker)
    bs[11:13] = SEC.to_bytes(2, "little")             # bytes per sector
    bs[13] = 1                                        # sectors per cluster
    bs[14:16] = RESERVE.to_bytes(2, "little")         # reserved sectors
    bs[16] = 2                                        # FAT count
    bs[17:19] = ROOT_ENTRIES.to_bytes(2, "little")    # root entries
    bs[19:21] = total_sectors.to_bytes(2, "little")   # TotSec16
    bs[21] = 0xF8                                     # media descriptor
    bs[22:24] = FATSZ.to_bytes(2, "little")           # FatSz16
    bs[24:26] = (63).to_bytes(2, "little")            # sectors per track
    bs[26:28] = (255).to_bytes(2, "little")           # heads
    bs[28:32] = (0).to_bytes(4, "little")             # hidden sectors
    bs[36] = 0x80                                     # drive number
    bs[38] = 0x29                                     # extended boot signature
    bs[39:43] = (0x20250817).to_bytes(4, "little")    # volume id
    bs[43:54] = volume_label.encode("ascii").ljust(11, b" ")
    bs[54:62] = b"FAT16   "
    bs[510:512] = b"\x55\xAA"
    put(0, bytes(bs))

    # --- FATs (uint16 entries) ---------------------------------------------------
    EOC = 0xFFF8
    chains = {
        0: 0xFFF8,
        1: 0xFFFF,
        2: EOC,        # cluster 2 kept allocated-but-unused (harmless marker)
        3: EOC,        # /DOWNLOAD dir (1 cluster)
        4: 5, 5: EOC,  # /DOWNLOAD/TOOLPACK.EXE (2 clusters)
        6: EOC,        # /README.TXT
        7: EOC,        # /SYNTHETI.TXT
    }
    fat1 = bytearray(FATSZ * SEC)
    for idx, val in chains.items():
        fat1[idx * 2:(idx + 1) * 2] = val.to_bytes(2, "little")
    put(RESERVE, bytes(fat1))
    put(RESERVE + FATSZ, bytes(fat1))

    def sector_of_cluster(n: int) -> int:
        return DATA_START + (n - 2)

    def put_file(cluster: int, data: bytes, fixed_len: int):
        n_clusters = max(1, (fixed_len + SEC - 1) // SEC)
        buf = bytearray(n_clusters * SEC)
        buf[:len(data)] = data
        s = sector_of_cluster(cluster) * SEC
        img[s:s + len(buf)] = buf

    readme_text = (
        "SYNTHETIC DEMO FIXTURE - NOT REAL EVIDENCE\n"
        "===========================================\n"
        "This removable-drive volume was generated by ArtifactIQ purely as demo\n"
        "evidence for phase 6 (disk-image analysis). It represents no real system.\n"
        "Files inside are staged props. Use only inside ArtifactIQ.\n"
    ).encode()
    synth_text = (
        "This file and this filesystem are synthetic.\n"
        "ArtifactIQ demo only - never mix with real evidence.\n"
    ).encode()
    toolpack = b"SYNTHETIC-DEMO-EXECUTABLE\x00" * 24   # 648 bytes -> 2 clusters

    root = _dir_entry("AIQDEMO", "   ", 0x08, 0, 0, dt)     # volume label
    root += _dir_entry("README", "TXT", 0x20, 6, len(readme_text), dt)
    root += _dir_entry("SYNTHETI", "TXT", 0x20, 7, len(synth_text), dt)
    root += _dir_entry("DOWNLOAD", "   ", 0x10, 3, 0, dt)
    root += b"\x00" * 32                                    # end-of-directory marker

    dld = _dir_entry(".", "   ", 0x10, 3, 0, dt)
    dld += _dir_entry("..", "   ", 0x10, 2, 0, dt)
    dld += _dir_entry("TOOLPACK", "EXE", 0x20, 4, len(toolpack), dt)
    dld += b"\x00" * 32

    put(RESERVE + FATSZ * 2, bytes(root))   # root dir lives in its fixed region
    put_file(3, bytes(dld), len(dld))       # /DOWNLOAD dir at cluster 3
    put_file(4, toolpack, len(toolpack))
    put_file(6, readme_text, len(readme_text))
    put_file(7, synth_text, len(synth_text))

    path.write_bytes(bytes(img))
    return {"sectors": total_sectors, "clusters": NCLUSTER,
            "fs": "FAT16", "label": volume_label, "files_written": 3}



