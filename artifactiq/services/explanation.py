"""Local-first, evidence-grounded explanation layer (Phase 11).

Every sentence cites concrete evidence references from the structured case
data already stored locally. No remote calls, no invention of facts.
Optional remote LLM: only when the operator sets ARTIFACTIQ_LLM_ENABLED=1 AND
provides ARTIFACTIQ_LLM_URL + key; only derived summaries travel, never raw
evidence bytes, and the analysis output says this explicitly.
"""
from __future__ import annotations

import json
import os
import urllib.request

from ..db import query, one, jload
from ..util.ids import now_iso, truncate

EXPLANER_VERSION = "explainer/2025b/1.0"


def _f(ev_row, k):
    v = ev_row[k] if k in ev_row.keys() else None
    return v


def narrative(case_id: str) -> dict:
    case = one("SELECT * FROM cases WHERE id=?", (case_id,))
    if not case:
        raise ValueError("case not found")
    ev_meta = query("SELECT * FROM evidence WHERE case_id=?", (case_id,))
    runs = [dict(r) for r in query("SELECT * FROM parser_runs WHERE case_id=?", (case_id,))]
    findings = [dict(r) for r in query(
        "SELECT * FROM findings WHERE case_id=? ORDER BY severity DESC", (case_id,))]
    mappings = [dict(r) for r in query("SELECT * FROM attack_mappings WHERE case_id=?", (case_id,))]
    branches = [dict(r) for r in query(
        "SELECT * FROM branches WHERE case_id=? ORDER BY priority DESC", (case_id,))]
    ts_stats = one(
        "SELECT COUNT(*) AS n, MIN(ts_utc) AS lo, MAX(ts_utc) AS hi FROM events "
        "WHERE case_id=? AND ts_utc IS NOT NULL", (case_id,))
    unknown_ts = one(
        "SELECT COUNT(*) AS n FROM events WHERE case_id=? AND ts_utc IS NULL", (case_id,))["n"]

    sentences: list[str] = []
    with_cite: list[dict] = []
    def s(text, cite=None):
        sentences.append(text)
        if cite:
            with_cite.append({"sentence": text, "cite": cite})

    if not ev_meta:
        s("No evidence has been registered, so no explanation can be produced.")
    else:
        names = "; ".join(f"{r['original_name']} ({r['media_type']}, sha256 {r['sha256'][:12]})" for r in ev_meta)
        s(f"This case contains {len(ev_meta)} registered evidence items: {names}.",
          {"evidence_ids": [r["id"] for r in ev_meta]})
        ok_ev = [r for r in runs if r["status"] == "completed"]
        bad_ev = [r for r in runs if r["status"] in ("failed", "unsupported", "skipped")]
        if runs:
            s(f"{len(ok_ev)} parser run(s) completed; "
              f"{len(bad_ev)} run(s) failed or were unsupported - the affected evidence is NOT covered by the analysis below.",
              {"parser_runs": [r["id"] for r in runs]})
        if ts_stats and ts_stats["n"]:
            s(f"The parsed timeline covers {ts_stats['n']} timestamped events between "
              f"{ts_stats['lo']} and {ts_stats['hi']} (UTC), with {unknown_ts} "
              f"event(s) lacking a trustworthy timestamp.",
              {"details": "events table; timestamps come from the artifact's own fields"})
        if findings:
            top = findings[0]
            s(f"The highest-severity finding is: {top['title']} (severity {top['severity']}). "
              f"It is supported by events {jload(top['event_ids'], [])[:6]}; interpretation "
              "stays with the investigator.",
              {"finding_id": top["id"], "evidence_ids": jload(top["evidence_ids"], [])})
            for f in findings[1:6]:
                s(f"Finding: {f['title']} (severity {f['severity']}).")
        else:
            s("No evidence-backed findings were generated by version " + "attack-rules/2025a" +
              "; either the rules did not fire, or the parsed evidence does not contain the "
              "related event types.")
        if mappings:
            techniques = ", ".join(f"{m['technique_id']} {m['technique_name']}" for m in mappings[:8])
            s(f"Rule-backed ATT&CK mappings: {techniques}. Each mapping re-checkable "
              f"under {mappings[0]['rule_version']}.")
        else:
            s("No ATT&CK mappings were supported; absent evidence means absent mappings (not safety).")
        if branches:
            top_b = branches[0]
            s(f"The next-step suggestion with the highest priority is: {top_b['question']} "
              f"(priority {top_b['priority']}, computed by {top_b['rule_id']}).",
              {"branch_id": top_b["id"]})
        gaps = [r["parser"] + " over " + (one("SELECT original_name FROM evidence WHERE id=?", (r["evidence_id"],)) or {"original_name": r["evidence_id"]})["original_name"]
                for r in runs if r["status"] in ("failed", "unsupported")]
        if gaps:
            s("Data gaps that limit confidence: " + "; ".join(gaps) + ".")
        s("All statements above are grounded in stored case rows and did not come from a model.")

    return {
        "case_id": case_id, "generated_at": now_iso(), "version": EXPLANER_VERSION,
        "sentences": sentences, "cites": with_cite,
        "findings_count": len(findings), "mappings_count": len(mappings),
        "branches_count": len(branches),
        "llm_used": False,
        "disclaimer": "All output is advisory and grounded in local structured rows; no claim "
                      "of attacker intent, exfiltration, or future behavior is made.",
    }


def llm_active() -> bool:
    return bool(os.environ.get("ARTIFACTIQ_LLM_ENABLED") == "1"
                and os.environ.get("ARTIFACTIQ_LLM_URL"))


def llm_summarize(case_id: str) -> dict:
    """Optional remote-AI pass. Disabled unless env explicitly enables it.

    Only the structured narrative sentences (command lines truncated, URLs
    redacted) are sent. Raw evidence bytes, full command lines, and custody
    hashes never leave the workstation. Output is advisory and can never
    modify evidence or custody records.
    """
    if not llm_active():
        return {"llm_used": False,
                "note": "Remote LLM disabled by configuration (ARTIFACTIQ_LLM_ENABLED)."}
    summary = narrative(case_id)
    compact = [
        {"t": raw_sent[:240]}
        for raw_sent in summary["sentences"]
    ]
    text = json.dumps({"sents": compact, "task": "clarify investigative narrative; do not invent facts"})
    data = text.encode()
    url = os.environ["ARTIFACTIQ_LLM_URL"]
    key = os.environ.get("ARTIFACTIQ_LLM_KEY", "")
    req = urllib.request.Request(url, data=data, method="POST")
    req.add_header("Authorization", f"Bearer {key}")
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            body = resp.read().decode("utf-8", errors="replace")
    except OSError as exc:
        return {"llm_used": False, "error": f"LLM request failed; local summary retained ({exc})."}
    return {
        "llm_used": True,
        "model": os.environ.get("ARTIFACTIQ_LLM_MODEL", "unknown"),
        "response": body[:4000],
        "grounded_in": summary["cites"],
        "disclaimer": "AI output is advisory; it cannot modify evidence or custody records.",
    }
